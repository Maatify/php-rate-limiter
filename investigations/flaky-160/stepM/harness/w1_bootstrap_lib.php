// #160 phase 2b — W1 instrument (PLAN.md §2, §8 LT-160C-01), loaded by w1_bootstrap.php, which is passed to PHPUnit on the command line
// (`--bootstrap`), never written into phpunit.xml, tests/ or composer.json.
//
// It serves the class Maatify\RateLimiter\Repository\Redis\RedisFullCapabilityStore from a prepended
// autoloader as two parts:
//   1. the on-disk src/ file with the one recorded mechanical edit (store-transform.diff: `final class
//      RedisFullCapabilityStore` -> `class RedisFullCapabilityStoreInner`), after its sha256 is checked
//      against store.sha256 (the file's hash at main@2cf8565);
//   2. a `final class RedisFullCapabilityStore extends RedisFullCapabilityStoreInner` generated by
//      reflection from the same uniform template for every public method: record the call, call
//      parent::, record the return. No other logic. The one observation that is not a plain record is
//      the read-only checkBlock after a non-applied publication (LT-160C-02), made through
//      parent::checkBlock and never changing a returned value.
//
// Environment: FLAKY160B_DIR (out dir; the evaluated files and rec-<pid>.jsonl go there). Without it
// the process records nothing and writes nothing.

namespace Flaky160B {

    use ReflectionClass;
    use ReflectionMethod;
    use ReflectionNamedType;
    use ReflectionType;
    use ReflectionUnionType;
    use ReflectionIntersectionType;

    final class Rec
    {
        /** @var list<array<string, mixed>> */
        public static array $buf = [];
        public static int $seq = 0;
        public static int $depth = 0;
        public static string $phase = 'run';
        public static int $rootPid = 0;
        public static ?string $dir = null;
        public static int $pubCount = 0;
        public static int $bufPid = 0;
        /** @var array<string, true> */
        public static array $keys = [];
        /** @var list<array{int, object}> */
        public static array $stores = [];

        private static function own(): void
        {
            // A forked worker starts with the parent's buffer in memory: drop it, the parent flushes its own.
            if (self::$bufPid !== getmypid()) {
                self::$bufPid = getmypid();
                self::$buf = [];
                self::$seq = 0;
                self::$depth = 0;
                self::$pubCount = 0;
                self::$keys = [];
            }
        }

        public static function begin(string $method, array $args): array
        {
            self::own();
            return [self::$seq++, self::$depth++, hrtime(true), $method, $args];
        }

        public static function end(array $token, mixed $ret, ?\Throwable $e = null): void
        {
            self::$depth--;
            [$seq, $depth, $t0, $method, $args] = $token;
            self::$buf[] = [
                's' => $seq, 'd' => $depth, 't0' => $t0, 't1' => hrtime(true), 'm' => $method, 'p' => self::$phase,
                'a' => self::sum($args, 0), 'r' => self::sum($ret, 0), 'x' => $e === null ? null : $e::class,
            ];
        }

        public static function note(string $kind, array $data): void
        {
            self::own();
            self::$buf[] = ['s' => self::$seq++, 'd' => self::$depth, 't0' => hrtime(true), 't1' => hrtime(true), 'm' => '#' . $kind, 'p' => self::$phase, 'a' => self::sum($data, 0), 'r' => null, 'x' => null];
        }

        public static function sum(mixed $v, int $level): mixed
        {
            if (is_scalar($v) || $v === null) {
                return $v;
            }
            if (is_array($v)) {
                if ($level >= 2) {
                    return 'array(' . count($v) . ')';
                }
                $out = [];
                foreach (array_slice($v, 0, 12, true) as $k => $x) {
                    $out[$k] = self::sum($x, $level + 1);
                }
                return $out;
            }
            if (is_object($v)) {
                $short = substr(strrchr('\\' . $v::class, '\\'), 1);
                if ($level >= 2) {
                    return $short;
                }
                $out = ['_' => $short];
                foreach (get_object_vars($v) as $k => $x) {
                    $out[$k] = self::sum($x, $level + 1);
                }
                return $out;
            }
            return gettype($v);
        }

        public static function flush(): void
        {
            if (self::$dir === null || self::$buf === []) {
                return;
            }
            $lines = '';
            foreach (self::$buf as $r) {
                $lines .= json_encode($r, JSON_UNESCAPED_SLASHES | JSON_INVALID_UTF8_SUBSTITUTE) . "\n";
            }
            $lines .= json_encode(['m' => '#end', 'n' => count(self::$buf), 'pid' => getmypid(), 'root' => getmypid() === self::$rootPid]) . "\n";
            file_put_contents(self::$dir . '/rec-' . (getmypid() === self::$rootPid ? 'root-' : '') . getmypid() . '.jsonl', $lines, FILE_APPEND);
            self::$buf = [];
        }

        public static function exitReads(): void
        {
            // Worker exit (LT-160C-02): one read of each K4/K5 key the worker's store touched. Only forked workers.
            if (getmypid() === self::$rootPid || self::$keys === []) {
                return;
            }
            $store = null;
            foreach (array_reverse(self::$stores) as [$pid, $s]) {
                if ($pid === getmypid()) {
                    $store = $s;
                    break;
                }
            }
            if ($store === null) {
                return;
            }
            self::$phase = 'exit';
            foreach (array_keys(self::$keys) as $key) {
                try {
                    $store->checkBlock((string) $key);
                } catch (\Throwable) {
                }
            }
        }
    }

    final class Gen
    {
        public static function type(?ReflectionType $t): string
        {
            if ($t === null) {
                return '';
            }
            if ($t instanceof ReflectionNamedType) {
                $n = $t->getName();
                $builtin = $t->isBuiltin() || in_array($n, ['self', 'static', 'parent'], true);
                $n = $builtin ? $n : '\\' . $n;
                return ($t->allowsNull() && $n !== 'mixed' && $n !== 'null') ? '?' . $n : $n;
            }
            $sep = $t instanceof ReflectionUnionType ? '|' : '&';
            return implode($sep, array_map(static fn(ReflectionType $x): string => self::type($x), $t->getTypes()));
        }

        /** @return string PHP source (no opening tag) of the recording subclass */
        public static function subclass(string $inner, string $ns, string $short): string
        {
            $rc = new ReflectionClass($inner);
            $out = "namespace $ns;\n\nclass $short extends {$short}Inner\n{\n";
            $out .= "    public function __construct(...\$args)\n    {\n        parent::__construct(...\$args);\n"
                . "        \\Flaky160B\\Rec::\$stores[] = [getmypid(), \$this];\n    }\n\n";
            foreach ($rc->getMethods(ReflectionMethod::IS_PUBLIC) as $m) {
                if ($m->isStatic() || $m->isConstructor() || str_starts_with($m->getName(), '__') || $m->getDeclaringClass()->getName() !== $inner) {
                    continue;
                }
                $params = [];
                $call = [];
                $arr = [];
                foreach ($m->getParameters() as $p) {
                    $s = self::type($p->getType());
                    $s .= ($s === '' ? '' : ' ') . ($p->isVariadic() ? '...' : '') . '$' . $p->getName();
                    if ($p->isDefaultValueAvailable()) {
                        $s .= ' = ' . var_export($p->getDefaultValue(), true);
                    }
                    $params[] = $s;
                    $call[] = ($p->isVariadic() ? '...' : '') . '$' . $p->getName();
                    $arr[] = $p->isVariadic() ? '...$' . $p->getName() : '$' . $p->getName();
                }
                $ret = self::type($m->getReturnType());
                $name = $m->getName();
                $void = $ret === 'void';
                $out .= '    public function ' . $name . '(' . implode(', ', $params) . ')' . ($ret === '' ? '' : ': ' . $ret) . "\n    {\n";
                $out .= "        \$__t = \\Flaky160B\\Rec::begin('$name', [" . implode(', ', $arr) . "]);\n";
                $out .= "        try {\n            " . ($void ? '' : '$__r = ') . "parent::$name(" . implode(', ', $call) . ");\n"
                    . "        } catch (\\Throwable \$__e) {\n            \\Flaky160B\\Rec::end(\$__t, null, \$__e);\n            throw \$__e;\n        }\n";
                $out .= "        \\Flaky160B\\Rec::end(\$__t, " . ($void ? 'null' : '$__r') . ");\n";
                if ($name === 'blockWithPunishmentLifecycleTrackingAt') {
                    $out .= "        \\Flaky160B\\Rec::\$keys[\$currentKey] = true;\n"
                        . "        if (! \$__r->applied) {\n            \$this->__flaky160bObserve(\$currentKey, ++\\Flaky160B\\Rec::\$pubCount);\n        }\n";
                }
                if (preg_match('/^mutateGenerationBoundScore(At)?$/', $name)) {
                    $out .= "        \\Flaky160B\\Rec::\$keys[\$currentKey] = true;\n";
                }
                if (preg_match('/^increment(At)?$/', $name)) {
                    $out .= "        \\Flaky160B\\Rec::\$keys[\$key] = true;\n";
                }
                $out .= $void ? "        return;\n" : "        return \$__r;\n";
                $out .= "    }\n\n";
            }
            $out .= "    /** LT-160C-02: read-only block read after a non-applied publication; records, changes nothing. */\n"
                . "    public function __flaky160bObserve(string \$key, int \$n): void\n    {\n"
                . "        \\Flaky160B\\Rec::\$phase = 'obs';\n        try {\n            \$b = parent::checkBlock(\$key);\n"
                . "            \\Flaky160B\\Rec::note('obs', ['n' => \$n, 'key' => \$key, 'level' => \$b?->level, 'expiresAt' => \$b?->expiresAt]);\n"
                . "        } finally {\n            \\Flaky160B\\Rec::\$phase = 'run';\n        }\n    }\n}\n";
            return $out;
        }
    }

    final class W1
    {
        public const FQCN = 'Maatify\\RateLimiter\\Repository\\Redis\\RedisFullCapabilityStore';
        private const EDIT_FROM = 'final class RedisFullCapabilityStore implements';
        private const EDIT_TO = 'class RedisFullCapabilityStoreInner implements';

        public static function install(string $root, ?string $dir): void
        {
            Rec::$dir = $dir;
            Rec::$rootPid = getmypid();
            $file = $root . '/src/Repository/Redis/RedisFullCapabilityStore.php';
            $pin = trim((string) file_get_contents(__DIR__ . "/store.sha256"));
            $text = (string) file_get_contents($file);
            if (hash('sha256', $text) !== $pin) {
                fwrite(STDERR, "V-TRANSFORM FAIL: src store file differs from main@2cf8565 (sha256 pin)\n");
                exit(3);
            }
            $count = 0;
            $evaluated = str_replace(self::EDIT_FROM, self::EDIT_TO, $text, $count);
            if ($count !== 1) {
                fwrite(STDERR, "V-TRANSFORM FAIL: the mechanical edit matched $count times, not once\n");
                exit(3);
            }
            $tmp = $dir ?? sys_get_temp_dir() . '/flaky160b-' . getmypid();
            @mkdir($tmp, 0777, true);
            $innerFile = $tmp . '/RedisFullCapabilityStore.evaluated.php';
            file_put_contents($innerFile, $evaluated);

            spl_autoload_register(static function (string $class) use ($root, $innerFile, $tmp): void {
                if ($class !== self::FQCN) {
                    return;
                }
                require $innerFile;
                $ns = 'Maatify\\RateLimiter\\Repository\\Redis';
                $src = Gen::subclass($ns . '\\RedisFullCapabilityStoreInner', $ns, 'RedisFullCapabilityStore');
                $subFile = $tmp . '/RedisFullCapabilityStore.recording.php';
                file_put_contents($subFile, "<?php\n\ndeclare(strict_types=1);\n\n" . $src);
                require $subFile;
                if (! class_exists(self::FQCN, false)) {
                    // Falling through would silently serve the unrecorded original from Composer.
                    fwrite(STDERR, "W1 FAIL: the recording class was not defined\n");
                    exit(3);
                }
            }, true, true);

            // Load it once, here, before any fork: a worker must never generate or load it itself (found in
            // the smoke: workers racing on the generated file fell through to Composer's original class).
            class_exists(self::FQCN);
            if ((new \ReflectionClass(self::FQCN))->getFileName() === $file || ! is_subclass_of(self::FQCN, self::FQCN . 'Inner')) {
                fwrite(STDERR, "W1 FAIL: the served class is not the recording subclass\n");
                exit(3);
            }

            if ($dir !== null) {
                register_shutdown_function(static function (): void {
                    Rec::exitReads();
                    Rec::flush();
                });
            }
        }
    }
