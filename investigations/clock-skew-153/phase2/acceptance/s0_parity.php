<?php

declare(strict_types=1);

/*
 * #153 phase 2, gate §4.5: the six #156 S-BEN / S-RA cells at σ = AA on the fix
 * head (expected/E-SAME/s0/) against the archived pre-fix outputs
 * (investigations/clock-mixes-153/expected/E-SAME/). argv: package root [, expected dir].
 * Writes <expected>/s0-summary.md. Registered before the run:
 *   * per stream j and twin (S, Z), the sequence of (op, primary) over the rows
 *     whose op is check, fail, success or claim, in file order;
 *     primary = decision | re-entry | exception, as #156;
 *   * a stream-twin whose sequence differs is attributed to the defect when the
 *     pre-fix sequence has an exception at or before the first differing step
 *     (validator or #155), and unattributed otherwise;
 *   * PASS: 0 unattributed differences and 0 exceptions on the fix head.
 *     lv / retryAfter differences with an equal primary are listed, not gated.
 * The two runs are separate in time, so a step close to a whole-second boundary
 * can fall either side in either run; any such unattributed difference is
 * listed with its step, times and values, for a ruling.
 */

[$self, $root, $expected] = $argv + [null, null, null];
$expected ??= __DIR__ . '/expected';
$before = $root . '/investigations/clock-mixes-153/expected/E-SAME';
$after = $expected . '/E-SAME/s0';
$cells = ['S-BEN_LOGIN-NA_AA', 'S-RA_LOGIN-NA_AA', 'S-BEN_CYCLE-NA_AA', 'S-RA_CYCLE-NA_AA', 'S-BEN_LOGIN_AA', 'S-RA_LOGIN_AA'];

/** @return \Generator<int, array<string, mixed>> */
function rows(string $file): \Generator
{
    $path = is_file($file) ? $file : $file . '.gz';
    $gz = str_ends_with($path, '.gz');
    $handle = $gz ? gzopen($path, 'rb') : fopen($path, 'rb');
    if ($handle === false) {
        throw new \RuntimeException('cannot open ' . $file);
    }
    while (($line = $gz ? gzgets($handle) : fgets($handle)) !== false) {
        if (trim($line) !== '') {
            yield json_decode($line, true, 512, JSON_THROW_ON_ERROR);
        }
    }
}

function primary(array $row): string
{
    return ($row['d'] ?? '-') . '|' . (($row['re'] ?? null) !== null ? 're' : '') . '|' . (isset($row['x']) ? 'x' : '');
}

/** @return array{meta: array<string, mixed>, seq: array<string, list<array<string, mixed>>>} */
function sequences(string $file): array
{
    $meta = [];
    $seq = [];
    foreach (rows($file) as $row) {
        if (isset($row['meta'])) {
            $meta = $row['meta'];
            continue;
        }
        if (! isset($row['j'], $row['t'], $row['op']) || ! in_array($row['op'], ['check', 'fail', 'success', 'claim'], true)) {
            continue;
        }
        $seq[$row['j'] . '|' . $row['t']][] = $row;
    }

    return ['meta' => $meta, 'seq' => $seq];
}

$md = ['# #153 phase 2 — gate §4.5, S0 non-regression (generated by `phase2/acceptance/s0_parity.php`; do not edit)', ''];
$md[] = 'Pre-fix: `investigations/clock-mixes-153/expected/E-SAME/` (#156, base `1e951ee`). Fix head: `expected/E-SAME/s0/`. Rules in the header of `s0_parity.php`.';
$md[] = '';
$md[] = '| Cell | stream-twins | equal | differ, attributed | differ, unattributed | lv / retryAfter only | exceptions before (S, Z) | exceptions after | verdict |';
$md[] = '| --- | ---: | ---: | ---: | ---: | ---: | --- | ---: | --- |';
$detail = [];
$allPass = true;
foreach ($cells as $cell) {
    if (! is_file("$after/$cell.jsonl") && ! is_file("$after/$cell.jsonl.gz")) {
        $md[] = sprintf('| `%s` | — | — | — | — | — | — | — | **FAIL (missing)** |', $cell);
        $allPass = false;
        continue;
    }
    $pre = sequences("$before/$cell.jsonl");
    $post = sequences("$after/$cell.jsonl");
    $c = ['n' => 0, 'equal' => 0, 'attr' => 0, 'unattr' => 0, 'secondary' => 0, 'exPre' => ['S' => 0, 'Z' => 0], 'exPost' => 0];
    $keys = array_unique(array_merge(array_keys($pre['seq']), array_keys($post['seq'])));
    sort($keys, SORT_NATURAL);
    foreach ($keys as $key) {
        $a = $pre['seq'][$key] ?? [];
        $b = $post['seq'][$key] ?? [];
        $c['n']++;
        foreach ($a as $row) {
            $c['exPre'][explode('|', $key)[1]] += isset($row['x']) ? 1 : 0;
        }
        foreach ($b as $row) {
            $c['exPost'] += isset($row['x']) ? 1 : 0;
        }
        $first = null;
        for ($i = 0; $i < max(count($a), count($b)); $i++) {
            if (! isset($a[$i], $b[$i]) || $a[$i]['op'] !== $b[$i]['op'] || primary($a[$i]) !== primary($b[$i])) {
                $first = $i;
                break;
            }
        }
        if ($first === null) {
            $c['equal']++;
            $secondary = false;
            foreach ($a as $i => $row) {
                $secondary = $secondary || ($row['lv'] ?? null) !== ($b[$i]['lv'] ?? null) || ($row['ra'] ?? null) !== ($b[$i]['ra'] ?? null);
            }
            $c['secondary'] += $secondary ? 1 : 0;
            continue;
        }
        $attributed = false;
        foreach (array_slice($a, 0, $first + 1) as $row) {
            $attributed = $attributed || isset($row['x']);
        }
        $c[$attributed ? 'attr' : 'unattr']++;
        if (! $attributed && count($detail) < 40) {
            $x = $a[$first] ?? null;
            $y = $b[$first] ?? null;
            $detail[] = sprintf(
                '* `%s` stream %s step %d: before %s %s (h0 %s, ra %s), after %s %s (h0 %s, ra %s)',
                $cell,
                $key,
                $first,
                $x['op'] ?? '—',
                $x === null ? '—' : primary($x),
                $x === null ? '—' : sprintf('%.3f', fmod($x['h0'] - $pre['meta']['started'], 100000)),
                $x['ra'] ?? '—',
                $y['op'] ?? '—',
                $y === null ? '—' : primary($y),
                $y === null ? '—' : sprintf('%.3f', fmod($y['h0'] - $post['meta']['started'], 100000)),
                $y['ra'] ?? '—',
            );
        }
    }
    $pass = $c['unattr'] === 0 && $c['exPost'] === 0;
    $allPass = $allPass && $pass;
    $md[] = sprintf('| `%s` | %d | %d | %d | %d | %d | %d, %d | %d | %s |', $cell, $c['n'], $c['equal'], $c['attr'], $c['unattr'], $c['secondary'], $c['exPre']['S'], $c['exPre']['Z'], $c['exPost'], $pass ? 'PASS' : '**FAIL**');
}
if ($detail !== []) {
    $md[] = '';
    $md[] = '### Unattributed differences (first differing step; h0 in seconds since the cell started)';
    $md[] = '';
    array_push($md, ...$detail);
}
$md[] = '';
$md[] = '**Gate §4.5: ' . ($allPass ? 'PASS' : 'FAIL') . '**';
file_put_contents($expected . '/s0-summary.md', implode("\n", $md) . "\n");
echo ($allPass ? 'PASS' : 'FAIL'), " gate 4.5; wrote ", $expected, "/s0-summary.md\n";
