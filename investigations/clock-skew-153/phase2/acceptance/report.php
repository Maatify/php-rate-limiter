/** @return list<string> */
function cross(array $families, array $policies, array $sigmas): array
{
    $out = [];
    foreach ($families as $family) {
        foreach ($policies as $policy) {
            foreach ($sigmas as $sigma) {
                $out[] = $family . '_' . $policy . '_' . $sigma;
            }
        }
    }

    return $out;
}

function exists(string $file): bool
{
    return is_file($file) || is_file($file . '.gz');
}

/** @return \Generator<int, array<string, mixed>> */
function rows(string $file): \Generator
{
    $path = is_file($file) ? $file : $file . '.gz';
    $gz = str_ends_with($path, '.gz');
    $handle = $gz ? gzopen($path, 'rb') : fopen($path, 'rb');
    if ($handle === false) {
        throw new \RuntimeException('cannot open ' . $file);
    }
    while (($line = $gz ? gzgets($handle) : fgets($handle)) !== false) {
        if (trim($line) !== '') {
            yield json_decode($line, true, 512, JSON_THROW_ON_ERROR);
        }
    }
}

/** @return array<string, int> */
function p154Stats(string $file): array
{
    $validator = 'Maatify\RateLimiter\Exception\RateLimiterException: ' . VALIDATOR_MESSAGE;
    $s = ['requests' => 0, 'reached' => 0, 'validator' => 0, 'other' => 0, 'setup' => 0, 'setupExceptions' => 0, 'snaps' => 0, 'upLo' => 0, 'errors' => 0];
    foreach (rows($file) as $row) {
        if (isset($row['meta'])) {
            if (($row['meta']['scale'] ?? null) !== 1.0) {
                throw new \RuntimeException('cell ' . $row['meta']['cell'] . ' was run with scale ' . json_encode($row['meta']['scale']));
            }
            continue;
        }
        $s['errors'] += count($row['err'] ?? []);
        if ($row['setup'] ?? false) {
            $s['setup']++;
            $s['setupExceptions'] += $row['o'] === 'EXCEPTION' ? 1 : 0;
            continue;
        }
        $s['requests']++;
        $isValidator = ($row['x'] ?? null) === $validator;
        $s['validator'] += $isValidator ? 1 : 0;
        $s['other'] += $row['o'] === 'EXCEPTION' && ! $isValidator ? 1 : 0;
        $s['reached'] += $row['s'] !== [] ? 1 : 0;
        foreach ($row['s'] as $snap) {
            $s['snaps']++;
            $s['upLo'] += ($snap['UP'] ?? false) || ($snap['LO'] ?? false) ? 1 : 0;
            $s['errors'] += isset($snap['err']) ? 1 : 0;
        }
    }

    return $s;
}

function primary(array $row): string
{
    return ($row['d'] ?? '-') . '|' . (($row['re'] ?? null) !== null ? 're' : '') . '|' . (isset($row['x']) ? 'x' : '');
}

/** @return array<string, mixed> */
