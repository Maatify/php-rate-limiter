    $meta = null;
    $steps = [];
    foreach (rows($file) as $row) {
        if (isset($row['meta'])) {
            $meta = $row['meta'];
            continue;
        }
        if (isset($row['state']) || isset($row['end']) || ! isset($row['j'], $row['t'])) {
            continue;
        }
        $steps[$row['j']][$row['t']][] = $row;
    }
    if ($meta === null) {
        throw new \RuntimeException('no meta in ' . $file);
    }
    $sigma = is_numeric($meta['sigma']) ? abs((float) $meta['sigma']) : 0.0;
    $validator = VALIDATOR_MESSAGE;
    $s = ['meta' => $meta, 'streams' => count($steps), 'probeSteps' => 0, 'probeMissing' => 0, 'probeChanged' => 0, 'paired' => 0, 'pairedChanged' => 0,
        'secondary' => 0, 'exS' => 0, 'exZ' => 0, 'valS' => 0, 'valZ' => 0, 'changes' => []];
    ksort($steps);
    foreach ($steps as $j => $twins) {
        $bands = [];
        $byK = [];
        foreach (['S', 'Z'] as $t) {
            foreach ($twins[$t] ?? [] as $row) {
                if (isset($row['x'])) {
                    $s['ex' . $t]++;
                    $s['val' . $t] += str_contains((string) $row['x'], $validator) ? 1 : 0;
                }
                if (isset($row['probe'])) {
                    $bands[$row['probe']['band'] ?? '?'][$t] = $row;
                }
                if (isset($row['k'], $row['op'])) {
                    $byK[$row['k']][$t] ??= $row;
                }
            }
        }
        foreach ($bands as $band => $pair) {
            if (! isset($pair['S'], $pair['Z'])) {
                $s['probeMissing']++;
                continue;
            }
            $s['probeSteps']++;
            if (primary($pair['S']) !== primary($pair['Z'])) {
                $s['probeChanged']++;
                if (count($s['changes']) < 5) {
                    $s['changes'][] = sprintf('stream %d band %s: S %s, Z %s', $j, $band, primary($pair['S']), primary($pair['Z']));
                }
            } elseif (($pair['S']['lv'] ?? null) !== ($pair['Z']['lv'] ?? null) || abs((int) ($pair['S']['ra'] ?? 0) - (int) ($pair['Z']['ra'] ?? 0)) > (int) ceil($sigma)) {
                $s['secondary']++;
            }
        }
        foreach ($byK as $pair) {
            if (! isset($pair['S'], $pair['Z']) || $pair['S']['op'] !== $pair['Z']['op']) {
                continue;
            }
            $s['paired']++;
            $s['pairedChanged'] += primary($pair['S']) !== primary($pair['Z']) ? 1 : 0;
        }
    }

    return $s;
}

/** @return array<string, mixed> */
function quantization(string $file, string $family): array
{
    $sigma = 0.0;
    $bands = [];
    foreach (rows($file) as $row) {
        if (isset($row['meta'])) {
            $sigma = (float) $row['meta']['sigma'];
            continue;
        }
        if (isset($row['probe'], $row['j'], $row['t'])) {
            $bands[$row['j'] . '|' . ($row['probe']['band'] ?? '?')][$row['t']] = $row;
        }
    }
    $q = ['n' => 0, 'obsPred' => 0, 'obsNoPred' => 0, 'samePred' => 0, 'samePredSecondary' => 0, 'sameNoPred' => 0, 'ambObs' => 0, 'ambSame' => 0, 'delta' => []];
    foreach ($bands as $pair) {
        if (! isset($pair['S'], $pair['Z'])) {
            continue;
        }
        [$s, $z] = [$pair['S'], $pair['Z']];
        if ($family === 'P-B') {
            $endS = $s['probe']['uS'] + 1200 - $sigma;
            $endZ = $s['probe']['u0'] + 1200;
        } elseif (isset($s['block']['S']['E'], $s['block']['Z']['E'])) {
            $endS = $s['block']['S']['E'] - $sigma;
            $endZ = (float) $s['block']['Z']['E'];
        } else {
            continue;
        }
        $q['n']++;
        $delta = sprintf('%+.2f', $endS - $endZ);
        $q['delta'][$delta] = ($q['delta'][$delta] ?? 0) + 1;
        $changed = primary($s) !== primary($z);
        $predicted = ($s['h0'] < $endS) !== ($z['h0'] < $endZ);
        $ambiguous = ($endS >= $s['h0'] - 0.002 && $endS <= $s['h1'] + 0.002) || ($endZ >= $z['h0'] - 0.002 && $endZ <= $z['h1'] + 0.002);
        if ($ambiguous) {
            $q[$changed ? 'ambObs' : 'ambSame']++;
            continue;
        }
        $q[($changed ? 'obs' : 'same') . ($predicted ? 'Pred' : 'NoPred')]++;
        if (! $changed && $predicted && (($s['lv'] ?? null) !== ($z['lv'] ?? null) || ($s['ra'] ?? null) !== ($z['ra'] ?? null))) {
            $q['samePredSecondary']++;
        }
    }

    return $q;
}

/**
 * C-156-Q (PLAN §12.4) for one #156 probe cell.
 *
 * @return array<string, int|float>
 */
function c156q(string $file, string $cell): array
{
    [$family, $policy] = explode('_', $cell);
    $sigma = 0.0;
    $bands = [];
    $byK = [];
    $q = ['n' => 0, 'exceptions' => 0, 'primaryExplained' => 0, 'primaryUnexplained' => 0, 'maxDelta' => -1.0, 'raOne' => 0, 'raHandover' => 0, 'raUnexplained' => 0, 'lv' => 0];
    foreach (rows($file) as $row) {
        if (isset($row['meta'])) {
            $sigma = (float) $row['meta']['sigma'];
            continue;
        }
        if (! isset($row['j'], $row['t'])) {
            continue;
        }
        $q['exceptions'] += isset($row['x']) ? 1 : 0;
        if (isset($row['probe'])) {
            $bands[$row['j'] . '|' . ($row['probe']['band'] ?? '?')][$row['t']] = $row;
        }
        if (isset($row['k'], $row['op'])) {
            $byK[$row['j'] . '|' . $row['k']][$row['t']] ??= $row;
        }
    }
    $endModel = in_array($family, ['P-B', 'P-E2', 'P-E3'], true);
    foreach ($bands as $pair) {
        if (! isset($pair['S'], $pair['Z'])) {
            continue;
        }
        [$s, $z] = [$pair['S'], $pair['Z']];
        $q['n']++;
        $explainedByEnd = false;
        if ($endModel) {
            if ($family === 'P-B') {
                $endS = $s['probe']['uS'] + 1200 - $sigma;
                $endZ = $s['probe']['u0'] + 1200;
            } elseif (isset($s['block']['S']['E'], $s['block']['Z']['E'])) {
                $endS = $s['block']['S']['E'] - $sigma;
                $endZ = (float) $s['block']['Z']['E'];
            }
            if (isset($endS, $endZ)) {
                $q['maxDelta'] = max($q['maxDelta'], abs($endS - $endZ));
                $predicted = ($s['h0'] < $endS) !== ($z['h0'] < $endZ);
                $ambiguous = ($endS >= $s['h0'] - 0.002 && $endS <= $s['h1'] + 0.002) || ($endZ >= $z['h0'] - 0.002 && $endZ <= $z['h1'] + 0.002);
                $explainedByEnd = $predicted || $ambiguous;
            }
            unset($endS, $endZ);
        }
        if (primary($s) !== primary($z)) {
            $q[$explainedByEnd ? 'primaryExplained' : 'primaryUnexplained']++;
            continue;
        }
        $q['lv'] += ($s['lv'] ?? null) !== ($z['lv'] ?? null) ? 1 : 0;
        if (($s['ra'] ?? null) === ($z['ra'] ?? null)) {
            continue;
        }
        if (abs((int) ($s['ra'] ?? 0) - (int) ($z['ra'] ?? 0)) === 1) {
            $q['raOne']++;
        } elseif ($policy === 'CYCLE-NA' && in_array($family, ['P-E2', 'P-E3'], true) && $explainedByEnd) {
            $q['raHandover']++;
        } else {
            $q['raUnexplained']++;
        }
    }
    if ($family === 'P-I') {
        foreach ($byK as $pair) {
            if (isset($pair['S'], $pair['Z']) && $pair['S']['op'] === $pair['Z']['op'] && primary($pair['S']) !== primary($pair['Z'])) {
                $q['primaryUnexplained']++;
            }
        }
    }

    return $q;
}

/** @return array<string, mixed> */
function twoClock(string $file): array
{
    $validator = VALIDATOR_MESSAGE;
    $cells = [];
    $a2 = [];
    $control = ['n' => 0, 'x' => 0, 'refused' => 0];
    foreach (rows($file) as $row) {
        $arm = $row['arm'];
        if ($row['cell'] === 'TC-A2') {
            $a2[$arm] ??= ['n' => 0, 'requests' => 0, 'exceptions' => 0, 'withThrow' => 0, 'last' => []];
            $a2[$arm]['n']++;
            $a2[$arm]['requests'] += $row['requests'];
            $a2[$arm]['exceptions'] += $row['exceptions'];
            $a2[$arm]['withThrow'] += $row['exceptions'] > 0 ? 1 : 0;
            $a2[$arm]['last'][] = $row['lastThrowAfter'] === null ? 0.0 : 1000 * $row['lastThrowAfter'];
            if ($arm === 'control') {
                $control['n']++;
                $control['x'] += $row['exceptions'];
            }
            continue;
        }
        $key = $row['cell'] . '|' . $arm;
        $cells[$key] ??= ['ahead' => $row['ahead'], 'n' => 0, 'val' => 0, 'other' => 0, 'refused' => 0, 'o' => []];
        $r = $row['r'];
        $c = &$cells[$key];
        $c['n']++;
        $outcome = isset($r['x']) ? 'EXCEPTION' : $r['d'] . ($r['re'] ? '+re' : '');
        $c['o'][$outcome] = ($c['o'][$outcome] ?? 0) + 1;
        $isValidator = isset($r['x']) && str_contains($r['x'], $validator);
        $c['val'] += $isValidator ? 1 : 0;
        $c['other'] += isset($r['x']) && ! $isValidator ? 1 : 0;
        $refused = isset($r['x']) || $r['d'] !== 'ALLOW';
        $c['refused'] += $refused ? 1 : 0;
        // Controls: TC-A1 must not throw; TC-B / TC-E returns must be admitted.
        if ($arm === 'control') {
            $control['n']++;
            $control['x'] += isset($r['x']) || isset($row['w']['x']) || isset($row['writerLast']['x']) ? 1 : 0;
            $control['refused'] += $row['cell'] !== 'TC-A1' && $refused ? 1 : 0;
        }
        unset($c);
    }

    return ['cells' => $cells, 'a2' => $a2, 'control' => $control];
}

function wilson(int $x, int $n): string
{
    if ($n === 0) {
        return '—';
    }
    $z = 1.959964;
    $p = $x / $n;
    $den = 1 + $z * $z / $n;
    $centre = ($p + $z * $z / (2 * $n)) / $den;
    $half = $z * sqrt($p * (1 - $p) / $n + $z * $z / (4 * $n * $n)) / $den;

    return sprintf('%d / %d (%.1f %% [%.1f, %.1f])', $x, $n, 100 * $p, 100 * max(0, $centre - $half), 100 * min(1, $centre + $half));
}

/** @param list<float> $values */
function dist(array $values): string
{
    if ($values === []) {
        return '—';
    }
    sort($values);

    return sprintf('min %.1f / p50 %.1f / max %.1f', $values[0], $values[intdiv(count($values) - 1, 2)], $values[count($values) - 1]);
}

/** @param list<float> $values */
function median(array $values): float
{
    if ($values === []) {
        return NAN;
    }
    sort($values);

    return $values[intdiv(count($values) - 1, 2)];
}

/** @param array<string, int> $map */
function kv(array $map): string
{
    ksort($map);

    return implode('; ', array_map(static fn (string $k, int $v): string => '`' . $k . '` ' . $v, array_keys($map), $map));
}
