/** @return \Generator<int, array<string, mixed>> */
function rows(string $file): \Generator
{
    $path = is_file($file) ? $file : $file . '.gz';
    $handle = str_ends_with($path, '.gz') ? gzopen($path, 'rb') : fopen($path, 'rb');
    if ($handle === false) {
        throw new \RuntimeException('cannot open ' . $file);
    }
    while (($line = str_ends_with($path, '.gz') ? gzgets($handle) : fgets($handle)) !== false) {
        if (trim($line) !== '') {
            yield json_decode($line, true, 512, JSON_THROW_ON_ERROR);
        }
    }
}

/** @return array<string, mixed> */
function cellStats(iterable $rows, string $population): array
{
    $s = ['requests' => 0, 'reached' => 0, 'validator' => 0, 'other' => 0, 'agree' => 0, 'snaps' => 0, 'l867' => 0,
        'gap' => [], 'rtt' => [], 'gapTotal' => [], 'startToReply' => [], 'mMinusN' => [], 'deciles' => array_fill(0, 10, [0, 0]),
        'buckets' => [], 'bucketTotal' => [0, 0], 'site' => ['device' => [0, 0], 'occurrence' => [0, 0]], 'outcomes' => [],
        'prevHit' => 0, 'prevTotal' => 0, 'setup' => 0, 'setupExceptions' => 0];
    foreach ($rows as $row) {
        if (isset($row['meta'])) {
            if (($row['meta']['scale'] ?? null) !== 1.0 && getenv('C153_DRY_RUN') !== '1') {
                throw new \RuntimeException('cell ' . $row['meta']['cell'] . ' was run with scale ' . json_encode($row['meta']['scale']));
            }
            continue;
        }
        $validatorThrew = ($row['x'] ?? null) === EXPECTED_EXCEPTION;
        if ($row['setup'] ?? false) {
            $s['setup']++;
            $s['setupExceptions'] += $row['o'] === 'EXCEPTION' ? 1 : 0;
            continue;
        }
        $s['requests']++;
        $outcome = $row['x'] ?? $row['o'];
        $s['outcomes'][$outcome] = ($s['outcomes'][$outcome] ?? 0) + 1;
        $snaps = $row['s'];
        if ($row['o'] === 'EXCEPTION' && ! $validatorThrew) {
            $s['other']++;
        }
        if ($snaps === []) {
            continue;
        }
        $s['reached']++;
        $s['validator'] += $validatorThrew ? 1 : 0;
        $predicted = false;
        foreach ($snaps as $snap) {
            $s['snaps']++;
            $s['l867'] += $snap['ns'] === L867 ? 1 : 0;
            $hit = ($snap['UP'] ?? false) || ($snap['LO'] ?? false);
            $predicted = $predicted || $hit;
            $s['site'][$snap['si']][0]++;
            $s['site'][$snap['si']][1] += $hit ? 1 : 0;
        }
        $s['agree'] += $predicted === $validatorThrew ? 1 : 0;
        $first = $snaps[0];
        $s['gap'][] = ($first['ts'] - $first['ch']) * 1000;
        $s['rtt'][] = ($first['tr'] - $first['ts']) * 1000;
        $s['gapTotal'][] = ($first['tr'] - $first['ch']) * 1000;
        if (isset($row['st'])) {
            $s['startToReply'][] = ($first['tr'] - $row['st']) * 1000;
        }
        if (isset($first['M'], $first['N'])) {
            $s['mMinusN'][] = $first['M'] - $first['N'];
        }
        $decile = min(9, (int) floor(fmod($first['cn'], 1.0) * 10));
        $s['deciles'][$decile][0]++;
        $s['deciles'][$decile][1] += $validatorThrew ? 1 : 0;
        if (isset($row['dt'])) {
            $bucket = (int) floor($row['dt'] * 10);
            $s['buckets'][$bucket] ??= [0, 0];
            $s['buckets'][$bucket][0]++;
            $s['buckets'][$bucket][1] += $validatorThrew ? 1 : 0;
            $s['bucketTotal'][0]++;
            $s['bucketTotal'][1] += $validatorThrew ? 1 : 0;
        }
        if (array_key_exists('prevHit', $row)) {
            $s['prevTotal']++;
            $s['prevHit'] += $row['prevHit'] ? 1 : 0;
        }
    }
    ksort($s['buckets']);
    ksort($s['outcomes']);

    return $s;
}

function wilson(int $x, int $n): string
{
    if ($n === 0) {
        return '—';
    }
    $z = 1.959964;
    $p = $x / $n;
    $den = 1 + $z * $z / $n;
    $centre = ($p + $z * $z / (2 * $n)) / $den;
    $half = $z * sqrt($p * (1 - $p) / $n + $z * $z / (4 * $n * $n)) / $den;

    return sprintf('%.3f %% [%.3f, %.3f]', 100 * $p, 100 * max(0, $centre - $half), 100 * min(1, $centre + $half));
}

/** @param list<float> $values */
function dist(array $values): string
{
    if ($values === []) {
        return '—';
    }
    sort($values);
    $pick = static function (float $q) use ($values): float {
        return $values[max(0, (int) ceil($q * count($values)) - 1)];
    };

    return sprintf('min %.3f / p50 %.3f / p90 %.3f / p99 %.3f / max %.3f', $values[0], $pick(0.5), $pick(0.9), $pick(0.99), $values[count($values) - 1]);
}

/** @param list<int> $values @return array<int, int> */
function countValues(array $values): array
{
    $counts = array_count_values($values);
    ksort($counts);

    return $counts;
}

/** @param array<string, int> $map */
function kv(array $map): string
{
    ksort($map);

    return implode('; ', array_map(static fn (string $k, int $v): string => '`' . $k . '` ' . $v, array_keys($map), $map));
}

/** @param array<int, int> $map */
function kvInt(array $map): string
{
    return '{' . implode(', ', array_map(static fn (int $k, int $v): string => $k . ': ' . $v, array_keys($map), $map)) . '}';
}
